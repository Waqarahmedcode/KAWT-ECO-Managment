import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium, request } from '@playwright/test';
const base = 'http://127.0.0.1:3012';
const accounts = JSON.parse(fs.readFileSync(process.env.KAWT_LAB_EXISTING_ACCOUNTS));
const fixture = JSON.parse(fs.readFileSync('.local/laboratory-test-database.json'));
const source = JSON.parse(fs.readFileSync('.local/laboratory-july-source.json'));
const sourceCbc = source.payload.tests.find(t=>t.label==='CBC').morning;
const sourceTestTotal = source.payload.tests.reduce((n,t)=>n+t.morning+t.evening+t.night,0);
const output = '.local/laboratory-browser';fs.mkdirSync(output, { recursive: true, mode: 0o700 });
const browser = await chromium.launch({ headless: true, executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
const passed = [];
let admin, operator;
try {
 const anon = await request.newContext({ baseURL: base });
 assert.equal((await anon.get('/api/lab/reports')).status(), 401);
 assert.equal((await anon.post('/api/lab/reports', { data: source })).status(), 401);
 await anon.dispose();passed.push('anonymous lab reads and writes rejected');
 const login = async role => {
  const account = accounts.find(x => x.role === role);
  const api = await request.newContext({ baseURL: base });
  const result = await api.post('/api/auth/session', { data: { action: 'signin', email: account.email, password: account.password } });
  assert.equal(result.status(), 200, 'Existing isolated local Auth fixture sign-in');
  return api;
 };
 admin = await login('admin');
 const original = (await (await admin.get('/api/lab/reports?id=' + fixture.reportId)).json()).report;
 const saved = await admin.post('/api/lab/reports', { data: { ...source, id: original.id, revision: original.revision } });
 assert.equal(saved.status(), 200);passed.push('real source draft saved in disposable test database');
 operator = await login('donor');
 assert.equal((await operator.post('/api/lab/access', { data: { email: 'not-a-real-account@isolated.invalid', access: 'operator', active: true } })).status(), 403);
 const clinic = await operator.post('/api/patients', { data: {} });assert.equal(clinic.status(), 403);
 passed.push('lab operator cannot grant staff access or enter clinical patient workflow');
 const context = await browser.newContext({ storageState: await operator.storageState(), viewport: { width: 1440, height: 1100 } });
 const page = await context.newPage(), errors = [];
 page.on('pageerror', e => errors.push(e.message));
 await page.goto(base + '/lab');await page.getByRole('heading', { name: 'Lab entry aur performance' }).waitFor();
 assert.equal(await page.getByRole('heading', { name: 'Administrator tools' }).count(), 0);
 assert.equal(await page.getByRole('link', { name: 'Overall dashboard' }).count(), 0);
 await page.getByLabel('Saved reports').selectOption(fixture.reportId);
 await page.getByLabel('CBC Morning', { exact: true }).waitFor();
 assert.equal(await page.getByLabel('CBC Morning', { exact: true }).inputValue(), String(sourceCbc));
 assert.equal(await page.getByText(String(sourceTestTotal), { exact: true }).count(), 1);
 const input = page.getByLabel('CBC Morning', { exact: true });await input.fill(String(sourceCbc+1));
 await page.getByRole('button', { name: 'Correction save karein' }).click();
 await page.getByText('Report save ho gayi. Totals aur correction history update hain.').waitFor();
 const read = await operator.get('/api/lab/reports?id=' + fixture.reportId), after = (await read.json()).report;
 assert.equal(after.payload.tests.find(t => t.label === 'CBC').morning, sourceCbc+1);
 const back = await operator.post('/api/lab/reports', { data: { ...source, id: after.id, revision: after.revision } });assert.equal(back.status(), 200);
 await page.reload();await page.getByLabel('Saved reports').selectOption(fixture.reportId);await page.getByLabel('CBC Morning', { exact: true }).waitFor();
 await page.getByLabel('Search tests').fill('CBC');assert.equal(await page.getByLabel('CBC Morning', { exact: true }).count(), 1);await page.getByLabel('Search tests').fill('');
 await page.evaluate(() => window.scrollTo(0, 0));
 await page.screenshot({ path: output + '/private-lab-desktop.png', fullPage: true });
 await page.setViewportSize({ width: 390, height: 844 });assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
 await page.screenshot({ path: output + '/private-lab-mobile.png', fullPage: true });
 await page.goto(base + '/dashboard');await page.waitForURL('**/lab');passed.push('department account returns to lab and has no other staff navigation');
 assert.deepEqual(errors, []);passed.push('authenticated source entry, correction save, search, desktop/mobile and no browser errors');
 await context.close();
 const unauthorized = await browser.newPage();await unauthorized.goto(base + '/lab');await unauthorized.waitForURL('**/lab/login');await unauthorized.getByRole('heading', { name: 'Laboratory sign-in' }).waitFor();await unauthorized.close();
 passed.push('private window redirects unsigned visitors to dedicated lab sign-in');
 fs.writeFileSync(output + '/results.json', JSON.stringify({ checks: passed, productRecordsCreated: 0, database: 'Disposable test database only' }, null, 2), { mode: 0o600 });
 passed.forEach(x => console.log('PASS:', x));
} finally { await admin?.dispose();await operator?.dispose();await browser.close(); }
